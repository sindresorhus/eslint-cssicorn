test({
	valid: [
		// Numerical curve solving can change an integer animation compared with the linear keyword.
		'a { animation: order 1s cubic-bezier(.3, .3, .8, .8); } @keyframes order { from { z-index: 0; } to { z-index: 1; } }',
		'a { animation: order 1s cubic-bezier(0, 0, 1, 1); } @keyframes order { from { z-index: 0; } to { z-index: 100000000; } }',
		// Pow and exp can round differently across a half-integer boundary.
		'a { scale: round(pow(e, 2.3513752571634776)); }',
		// An explicit logarithm base can use different precision than the natural logarithm.
		'a { z-index: round(log(1.6487212707001282, e)); }',
		// Hypot's squared intermediate can underflow before taking its square root.
		'a { opacity: sign(hypot(1e-30)); }',
		// Deferred browser comparisons can mask NaN differently when their arguments are flattened.
		'a { width: calc(min(1, min(sign(infinity * 1%), 0)) * 1px); }',
		'a { width: calc(max(0, max(sign(infinity * 1%), 1)) * 1px); }',
		// A later positive-zero operand does not replace an earlier negative zero in deferred max.
		'a { width: calc(1 / abs(max(sign(-1 * 0 * sign(1%)), 0)) * 1px); }',
	],
	invalid: [],
});

